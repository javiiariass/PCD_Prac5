    private final static int NUM_HILOS_LANZAR = 50;
    private final static int PORCENTAJE_HILOS_EFECTIVO = 3; // rango 1-10
    private final static int[] ANCHO_ALTO = {800, 400};
    private final static int NUM_TERMINAL_TARJETA = 2;
